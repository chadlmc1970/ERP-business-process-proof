def random_draws(n=240):
    print(f"\n## {n} random worlds, each parameter drawn from a stated range. A range is not a probability\n")
    r = random.Random(20261104)
    rows = []
    rivals = ("T", "T+", "A+", "U")
    metrics = ("buyer_total", "net50", "joint_total")
    wins = {m: {k: 0 for k in rivals + ("all",)} for m in metrics}
    keys = ("sup_recon", "inquiry_share", "noise", "buyer_low", "stale_rate", "dock_under", "claim_accept", "stop_late_share",
            "po_flip", "a_sample", "review_line_share", "sup_claim_cost", "opportunist")
    for i in range(n):
        over = dict(S2)
        over.update(
            sup_recon=r.uniform(0, 30), inquiry_share=r.uniform(0, 0.3), noise=r.uniform(0, 0.10),
            buyer_low=r.uniform(0.01, 0.15), stale_rate=r.uniform(0, 0.05), dock_under=r.uniform(0, 0.03),
            claim_accept=r.uniform(0.85, 1.0), stop_late_share=r.uniform(0.1, 1.0), l_fix=r.uniform(0.4, 0.95),
            po_flip=r.uniform(0, 0.6), a_sample=r.uniform(0.1, 0.5), review_line_share=r.uniform(0.1, 0.5),
            sup_claim_cost=r.uniform(30, 150), opportunist=r.choice([0.0, 0.0, 0.05, 0.2]),
        )
        over["l_audit_n"] = over["a_sample"] * over["a_n"] if "a_n" in over else over["a_sample"] * EXTRA["a_n"]
        res = scenario(over, seeds=(i + 1,), pols=rivals + ("L",), suppliers=100)
        row = {k: over[k] for k in keys}
        for m in metrics:
            lead = {k: res[k][m] - res["L"][m] for k in rivals}
            row[m] = min(lead[k] for k in ("T+", "A+", "U"))
            for k in rivals:
                wins[m][k] += lead[k] > 0
            wins[m]["all"] += row[m] > 0
        rows.append(row)
    print("Worlds where L is cheaper, by measure and rival:")
    for m in metrics:
        print(f"  {m}: " + ", ".join(f"{k} {v}/{n}" for k, v in wins[m].items()))

    def corr(a, b):
        ma, mb = statistics.mean(a), statistics.mean(b)
        va = sum((x - ma) ** 2 for x in a)
        vb = sum((y - mb) ** 2 for y in b)
        return sum((x - ma) * (y - mb) for x, y in zip(a, b)) / math.sqrt(va * vb) if va and vb else 0.0

    y = [row["net50"] for row in rows]
    cs = {k: corr([row[k] for row in rows], y) for k in keys}
    print("Correlation of each parameter with L's lead over its best rival at half pass-through:")
    for k, v in sorted(cs.items(), key=lambda kv: -abs(kv[1])):
        print(f"  {k}: {v:+.2f}")
    return dict(wins=wins, n=n, corr=cs, rows=rows)


