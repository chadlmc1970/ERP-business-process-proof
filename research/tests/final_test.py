"""Final test: the reviewer's engine with the rebuilt process added as S. Synthetic, no real data.

S, split settlement. The difference is worked inside payment terms, by the buyer, one case per
supplier per period. If it is still open at the due date, only the difference waits: the rest of
the invoice pays. A supplier never has to claim. Unlike U, the buyer has no foresight about which
differences are real, so every invoice above the record costs a line in the case. Small
differences pass at the same limit T+ uses, but a running one-sided sum per supplier revokes the
pass, so the limit is not a safe harbor. Invoices below the record pay as billed and the supplier
can rebill. A small random audit stays. Sc is S with the same clean data Tc gets. All the reviewer's frictions and rivals are unchanged.

Generated by build_final_test.py. Original notes from attack_lesser_of.py follow.

Written by the reviewer, not the proposer. Does not change simulate2.py. It imports simulate2 to
reuse its parameters, to probe its bugs, and to check that this engine reproduces it when the
attacks are switched off.

Differences from simulate2:
  common random numbers: every policy sees the same invoices, so differences are not RNG noise
  period-outer loop, so a claim queue can build up across suppliers
  new policies:
    T+  wide tolerance, one-sided (invoice below record passes), batched exception case,
        exception fixes the record. This is the simple improvement with the batching L was given.
    Tc  T+ plus cleaner master data (share of buyer record errors never happen)
    U   pay min(I, E) on time but the BUYER works the difference in a batch. No supplier claim.
        Isolates the payment rule from the shift of burden.
    A+  audit design that really samples: share of supplier-periods, small n, value floor,
        supplier debit memos allowed
    N   sanity baseline: hard gates only, pay every invoice as billed, no comparison, no audit.
        Any measure on which N looks best is not measuring control. Deadweight is such a measure.
    LS  L with a small-difference pass, stale-pattern detection by the buyer, buyer pays for
        its own errors. The narrow version tested in the verdict.
  new frictions, all off by default, see EXTRA.

Run: cd tests; python3 -I attack_lesser_of.py
Writes ../attack-results.json and prints the tables. All figures per 100,000 synthetic invoices.
"""
